"""Publish a self-contained snapshot of the generated safety documentation."""

import shutil
from pathlib import Path


def publish_safety(workspace):
    workspace = Path(workspace)
    source = workspace / 'build/docs/deploy'
    deploy = workspace / 'build/docs-general/deploy'
    target = deploy / 'safety'
    if not (source / 'html/workspace/applications/warmguard.html').is_file():
        return False
    if not deploy.is_dir():
        return False
    if target.is_symlink():
        if target.resolve() != source.resolve():
            raise ValueError(f'Documentation safety link points elsewhere: {target}')
        target.unlink()
    elif target.exists():
        if not target.is_dir() or not (target / '.warmguard-generated').is_file():
            raise ValueError(f'Documentation safety path is not a generated snapshot: {target}')
        shutil.rmtree(target)
    shutil.copytree(source, target)
    (target / '.warmguard-generated').write_text('Generated by west docs; safe to rebuild.\n')
    return True
